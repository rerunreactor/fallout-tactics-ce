// Draws `text` at (x, y) into an RGBA framebuffer, with a dark box behind it so
// it stays legible over any terrain.
inline void HudText(uint8_t* fb, int W, int H, int x, int y, const std::string& text,
                    uint8_t r = 255, uint8_t g = 255, uint8_t b = 255) {
    const int w = static_cast<int>(text.size()) * 6 + 2;
    for (int yy = y - 1; yy < y + 8 && yy < H; ++yy) {
        if (yy < 0) continue;
        for (int xx = x - 1; xx < x + w && xx < W; ++xx) {
            if (xx < 0) continue;
            uint8_t* p = fb + (static_cast<size_t>(yy) * W + xx) * 4;
            p[0] = static_cast<uint8_t>(p[0] / 4);
            p[1] = static_cast<uint8_t>(p[1] / 4);
            p[2] = static_cast<uint8_t>(p[2] / 4);
        }
    }
    int cx = x;
    for (char ch : text) {
        const int c = static_cast<unsigned char>(ch) - 32;
        if (c >= 0 && c < 95) {
            for (int col = 0; col < 5; ++col) {
                const uint8_t bits = kFont5x7[c][col];
                for (int row = 0; row < 7; ++row) {
                    if ((bits >> row) & 1) {
                        const int px = cx + col, py = y + row;
                        if (px < 0 || py < 0 || px >= W || py >= H) continue;
                        uint8_t* p = fb + (static_cast<size_t>(py) * W + px) * 4;
                        p[0] = r;
                        p[1] = g;
                        p[2] = b;
                        p[3] = 255;
                    }
                }
            }
        }
        cx += 6;
    }
}

